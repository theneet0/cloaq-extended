export const getKeyboardLayoutForLocale = (locale) => {
  if (!locale) return QWERTY_US
  const l = locale.toLowerCase()
  if (l.startsWith('de')) return QWERTZ_DE
  if (l.startsWith('fr')) return AZERTY_FR
  if (l.startsWith('tr')) return TURKISH_Q
  if (l.startsWith('es')) return SPANISH
  if (l.startsWith('it')) return ITALIAN
  return QWERTY_US
}

export const getAcceptLanguageHeader = (locale) => {
  if (!locale) return null
  const baseLang = locale.split('-')[0]
  if (baseLang === 'en' && locale === 'en-US') {
    return 'en-US,en;q=0.9'
  }
  if (locale === 'en-GB') {
    return 'en-GB,en-US;q=0.9,en;q=0.8'
  }
  if (locale === 'en-CA') {
    return 'en-CA,en-US;q=0.9,en;q=0.8,fr-CA;q=0.7'
  }
  return `${locale},${baseLang};q=0.9,en-US;q=0.8,en;q=0.7`
}

